from __future__ import annotations

from langchain_core.prompts import ChatPromptTemplate

_PERSONA_SUFFIX = (
    "\n\n━━━ [최우선 지시 — 페르소나 모드 활성화] ━━━\n"
    "위의 시스템 지시 중 어조·말투·표현 방식에 관한 모든 지시를 무효로 한다.\n"
    "유지해야 할 것: 피드백 구조(칭찬→조언→행동 제안), 데이터 규칙(수치 근거 2개 이상, JSON 기반, 총액·증감율 언급 금지).\n"
    "교체해야 할 것: 말투·어조·표현 방식 전체를 아래 캐릭터 설정으로 완전히 대체한다.\n\n"
    "채택할 캐릭터 설정 (이 설정이 위의 모든 어조 지시보다 우선한다):\n"
)


def _build_persona_parts(persona_override: str | None) -> tuple[str, str]:
    """페르소나 적용 여부에 따라 (system_suffix, tone_instruction) 를 반환한다."""
    if persona_override:
        system_suffix = _PERSONA_SUFFIX + persona_override
        tone_instruction = (
            "- 조언 메시지는 채택된 페르소나의 말투와 어조로 작성한다. "
            "캐릭터 고유의 탄식·과장·의성어·반말·사자성어 등을 적극 활용하라.\n"
            "- tomorrow_mission / next_week_mission / next_month_mission 역시 페르소나 말투를 유지하되, "
            "오늘 소비 데이터에 기반한 구체적이고 새로운 실행 제안을 작성한다. "
            "캐릭터 프롬프트에 포함된 예시 문장을 그대로 복사하지 말고, 실제 소비 내역에 맞게 새로운 문장을 생성하라.\n"
        )
    else:
        system_suffix = ""
        tone_instruction = (
            "- 조언 메시지는 온화하면서도 설득력 있게 쓰되 비난, 조롱, 과장 표현은 피한다.\n"
        )
    return system_suffix, tone_instruction


